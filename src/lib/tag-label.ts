/**
 * Slug -> nhãn hiển thị.
 *
 * Tag lạ (người dùng tự thêm qua form sửa bài) không có trong bảng thì thay dấu gạch
 * bằng khoảng trắng và viết hoa chữ đầu. Cách này KHÔNG khôi phục được dấu tiếng Việt —
 * đó là lý do mọi tag của giáo trình phải nằm trong bảng, và có test canh việc đó.
 */
export function nhanTag(tag: string): string {
  const co = NHAN[tag]
  if (co !== undefined) return co
  const thay = tag.replace(/-/g, ' ')
  return thay.charAt(0).toUpperCase() + thay.slice(1)
}

/** Dùng cho test: danh sách tag đã khai nhãn. */
export function tagDaKhaiNhan(): string[] {
  return Object.keys(NHAN)
}
